/**
 * Mock a POST request
 *
 * @summary Mocks a POST request to a url on the Holodeck server, returning a generated response with a 201 status, or
 * 204 when it has no body.
 */
export function POST(
  owner: object,
  url: string,
  response: ResponseGenerator,
  options?: Partial<Omit<Scaffold, 'response' | 'url' | 'method'>> & { RECORD?: boolean }
): Promise<void> {
  return mock(
    owner,
    {
      method: 'POST',
      url,
      scaffold: () => {
        const body = response();
        const status = options?.status ?? (body ? 201 : 204);

        return {
          status: status,
          statusText: options?.statusText ?? STATUS_TEXT_FOR.get(status) ?? '',
          headers: options?.headers ?? {},
          body: options?.body ?? null,
          method: 'POST',
          url,
          response: body,
        };
      },
    },
    options?.RECORD
  );
}

