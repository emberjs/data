/**
 * @module
 * @summary Helpers `GET`, `POST`, `PUT`, `PATCH`, `DELETE` and `HEAD` that register a mocked request and its response
 * with the Holodeck test server, plus the scaffold types they accept.
 */

import { mock } from '.';

/**
 * @summary Full description of a mocked request, its request body to match, and its response status, headers, and body,
 * as sent to the Holodeck server to record a fixture.
 * @public
 */
export interface Scaffold {
  status: number;
  statusText?: string;
  headers: Record<string, string>;
  body: Record<string, string> | string | null;
  method: string;
  url: string;
  response: Record<string, unknown>;
}

/**
 * @summary Function that builds a complete mock scaffold, accepted by `mock` in place of a `LazyScaffold`.
 * @public
 */
export type ScaffoldGenerator = () => Scaffold;

// JSON shape that permits arrays, objects, primitives, and null
type JSONPrimitive = string | number | boolean | null;
type JSONValue =
  | JSONPrimitive
  | { [k: string]: JSONValue }
  | JSONValue[];

/**
 * A mock whose method and url are known up front, with the rest of the
 * scaffold built only when holodeck is recording. This is what the mock
 * helpers pass, so that in replay mode a test's response generators never
 * run.
 *
 * @summary Mock whose method and url are known up front and whose full scaffold is built only when recording, as passed
 * by the Holodeck mock helpers to `mock`.
 * @public
 */
export interface LazyScaffold {
  method: string;
  url: string;
  scaffold: () => Scaffold;
}

/**
 * @summary Function passed to the Holodeck mock helpers that builds the response body, called only when recording a
 * fixture.
 * @public
 */
export type ResponseGenerator = () => JSONValue;

/**
 * Sets up Mocking for a GET request on the mock server
 * for the supplied url.
 *
 * The response body is generated by the supplied response function.
 *
 * Available options:
 * - status: the status code to return (default: 200)
 * - headers: the headers to return (default: {})
 * - body: the body to match against for the request (default: null)
 * - RECORD: record this request even when the suite is replaying, such as under CI (default: false).
 *   A local override for re-recording one request. Do not commit it; a committed RECORD means
 *   that request is never replayed against its fixture.
 *
 * @summary Mocks a GET request to a url on the Holodeck server, returning a generated response with a default 200
 * status.
 * @param url the url to mock, relative to the mock server host (e.g. `users/1`)
 * @param response a function which generates the response to return
 * @param options status, headers for the response, body to match against for the request, and whether to force recording
 * @return
 */
export function GET(
  owner: object,
  url: string,
  response: ResponseGenerator,
  options?: Partial<Omit<Scaffold, 'response' | 'url' | 'method'>> & { RECORD?: boolean }
): Promise<void> {
  return mock(
    owner,
    {
      method: 'GET',
      url,
      scaffold: () => ({
        status: options?.status ?? 200,
        statusText: options?.statusText ?? 'OK',
        headers: options?.headers ?? {},
        body: options?.body ?? null,
        method: 'GET',
        url,
        response: response(),
      }),
    },
    options?.RECORD
  );
}

